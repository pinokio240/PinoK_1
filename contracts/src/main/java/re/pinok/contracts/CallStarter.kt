package re.pinok.contracts

/**
 * #ARCH-CONTAINERS (Этап 1.3): запуск звонка из ядра (кнопки «Позвонить»
 * в шапке диалога/профиле). Контейнер :feature:calls публикует реализацию;
 * хост зовёт ТОЛЬКО если `registry.find<CallStarter>()` не пуст.
 *
 * ФАКТ замыкания (2026-09-02): текущие кнопки звонка в :app не запускают
 * звонок сами — они навигируют на экран звонка
 * (`Screen.Call.buildRoute(peerId, title, photo, incoming=false)`),
 * вся логика старта живёт в CallScreen. Поэтому контракт — минимальный
 * «намерение»: (кому, медиа-тип); title/photo и навигатор — забота хоста
 * (имплементация получает их через конструктор при регистрации в SovaApp,
 * ноль :app-типов в сигнатуре). video=true — запрос видеозвонка: текущий
 * UI-флоу звонит аудио (видео включается в звонке), флаг задел под фазу 2
 * (настоящая камера, контейнеры.план.md §2.2).
 */
interface CallStarter : Capability {
    /**
     * Запустить звонок.
     * @param peerId VK ID собеседника
     * @param video true = видеозвонок (сейчас UI-флоу стартует аудио; флаг — под §2.2)
     * @return true — звонок принят в работу (хост взял навигацию/старт);
     *         false — запуск сейчас невозможен (нет активного аккаунта/навигатора)
     */
    fun startCall(peerId: Long, video: Boolean): Boolean
}
